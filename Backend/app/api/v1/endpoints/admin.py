"""Admin dashboard API.

Three rules hold across every route here:

1. **Granular permissions.** Each route depends on one
   :class:`AdminPermission`; no route checks a role name.
2. **Narrow projections.** A support agent sees account and device metadata.
   Child usage and location need their own permissions, which no default role
   carries.
3. **Reads are audited too.** Looking up a family is itself a privileged act,
   so sensitive reads are written to the audit log alongside writes.
"""

