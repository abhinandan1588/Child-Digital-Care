@router.post(
    "/auth/login",
    response_model=ApiResponse[AdminLoginResponse],
    summary="Admin sign-in",
    dependencies=[Depends(RateLimit("admin.login.ip"))],
)
async def admin_login(
    payload: AdminLoginRequest,
    session: DbSession,
    client_ip: ClientIp,
    user_agent: UserAgent,
) -> dict:
    """A separate identity, session table and token audience from the parent
    API, so an admin credential is never interchangeable with a parent one.

    In production MFA is asserted by the identity provider or reverse proxy in
    front of this API; the session records whether it was satisfied. There is no
    server-side TOTP verifier here, and none is faked. See docs/DEPLOYMENT.md.
    """
    await check_rate_limit("admin.login.account", hash_identifier(str(payload.email)))

    result = await admin_service.authenticate_admin(
        session,
        email=str(payload.email),
        password=payload.password,
        mfa_code=payload.mfa_code,
        client_ip=client_ip,
        user_agent=user_agent,
    )
    return ok(
        AdminLoginResponse(
            access_token=result.session.access_token,
            refresh_token=result.session.refresh_token,
            expires_in=result.session.expires_in,
            refresh_expires_in=result.session.refresh_expires_in,
            admin=AdminOut(
                id=result.admin.id,
                email=result.admin.email,
                display_name=result.admin.display_name,
                status=result.admin.status.value,
                mfa_enrolled=result.admin.mfa_enrolled,
                roles=list(result.roles),
                permissions=sorted(result.permissions),
            ),
        ),
        message="Signed in.",
    )


@router.post(
    "/auth/refresh",
    response_model=ApiResponse[AdminTokenPair],
    summary="Rotate an admin session",
)
async def admin_refresh(
    payload: RefreshRequest, session: DbSession, client_ip: ClientIp, user_agent: UserAgent
) -> dict:
    outcome = await token_service.rotate_admin_session(
        session,
        raw_refresh_token=payload.refresh_token,
        user_agent=user_agent,
        ip_prefix=audit_service.ip_prefix(client_ip),
    )
    return ok(
        AdminTokenPair(
            access_token=outcome.issued.access_token,
            refresh_token=outcome.issued.refresh_token,
            expires_in=outcome.issued.expires_in,
            refresh_expires_in=outcome.issued.refresh_expires_in,
        ),
        message="Session refreshed.",
    )


@router.post(
    "/auth/logout",
    response_model=ApiResponse[GenericMessageOut],
    summary="Admin sign-out",
)
async def admin_logout(
    payload: LogoutRequest,
    principal: CurrentAdmin,
    session: DbSession,
    client_ip: ClientIp,
) -> dict:
    if payload.refresh_token:
        await token_service.revoke_admin_session_by_token(
            session, raw_refresh_token=payload.refresh_token
        )
    else:
        await token_service.revoke_all_admin_sessions(
            session, admin_user_id=principal.id, reason="logout"
        )
    await audit_service.record(
        session,
        action=AuditAction.ADMIN_LOGOUT,
        actor_type=AuditActorType.admin_user,
        actor_id=principal.id,
        actor_label=principal.admin.email,
        client_ip=client_ip,
    )
    return ok(GenericMessageOut(detail="Signed out."), message="Signed out.")


