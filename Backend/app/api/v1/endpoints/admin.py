@router.get(
    "/users",
    response_model=ApiResponse[Page[AdminUserListItem]],
    summary="Search users",
)
async def list_users(
    session: DbSession,
    principal: UsersRead,
    client_ip: ClientIp,
    q: Annotated[str | None, Query(description="Substring match on email.")] = None,
    account_status: Annotated[AccountStatus | None, Query()] = None,
    limit: Annotated[int, Query(ge=1, le=MAX_ADMIN_PAGE)] = 50,
    offset: Annotated[int, Query(ge=0)] = 0,
) -> dict:
    """The search itself is audited: who searched for what is part of the
    support-access trail."""
    items, total = await admin_service.search_users(
        session, query=q, status=account_status, limit=limit, offset=offset
    )
    await admin_service.record_sensitive_read(
        session,
        admin_id=principal.id,
        admin_email=principal.admin.email,
        action=AuditAction.ADMIN_USER_LIST_READ,
        client_ip=client_ip,
        metadata={"result_count": len(items), "filtered": bool(q or account_status)},
    )
    return ok(
        Page[AdminUserListItem](
            items=[AdminUserListItem(**item) for item in items],
            page_info=PageInfo(limit=limit, has_more=offset + len(items) < total, total=total),
        )
    )


@router.get(
    "/users/{user_id}",
    response_model=ApiResponse[AdminUserDetailOut],
    summary="Get one user",
)
async def get_user(
    user_id: uuid.UUID,
    session: DbSession,
    principal: UsersRead,
    client_ip: ClientIp,
) -> dict:
    """``timezone`` and other profile detail are withheld unless the caller holds
    ``users.pii.read``."""
    include_pii = principal.can(AdminPermission.USERS_PII_READ)
    data = await admin_service.user_detail(session, user_id=user_id, include_pii=include_pii)
    await admin_service.record_sensitive_read(
        session,
        admin_id=principal.id,
        admin_email=principal.admin.email,
        action=AuditAction.ADMIN_USER_READ,
        target_type="user",
        target_id=user_id,
        client_ip=client_ip,
        metadata={"included_pii": include_pii},
    )
    return ok(AdminUserDetailOut(**data))


