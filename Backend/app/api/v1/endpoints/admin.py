@router.post(
    "/devices/{device_id}/revoke",
    response_model=ApiResponse[GenericMessageOut],
    summary="Unlink a device (trust & safety action)",
)
async def admin_revoke_device(
    device_id: uuid.UUID,
    session: DbSession,
    principal: DevicesRevoke,
    client_ip: ClientIp,
) -> dict:
    """Used when a device must be unlinked without the account holder, for
    example on a confirmed non-consensual-monitoring report."""
    from app.core.errors import NotFound
    from app.db.models.device import Device

    device = await session.get(Device, device_id)
    if device is None:
        raise NotFound("Device not found.")

    await device_service.revoke_device(
        session,
        device=device,
        reason="revoked by trust & safety",
        actor_type=AuditActorType.admin_user,
        actor_id=principal.id,
        client_ip=client_ip,
    )
    return ok(GenericMessageOut(detail="Device unlinked."), message="Device unlinked.")


