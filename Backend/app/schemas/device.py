"""Device, pairing, capability and permission-report schemas."""

from __future__ import annotations

import uuid
from datetime import datetime

from pydantic import Field, field_validator

from app.db.enums import (
    CapabilityKey,
    CapabilitySupport,
    DevicePlatform,
    DeviceStatus,
    PairingInvitationStatus,
    PermissionKey,
    PermissionState,
    SyncStatus,
)
from app.schemas.common import OutSchema, SchemaBase, validate_timezone


# ---------------------------------------------------------------------------
# Pairing
# ---------------------------------------------------------------------------
class PairingInvitationCreate(SchemaBase):
    device_label: str | None = Field(
        default=None,
        max_length=80,
        description="Optional label applied to the device once it pairs.",
    )
    expires_in_minutes: int | None = Field(
        default=None,
        ge=1,
        le=60,
        description="Defaults to PAIRING_INVITATION_EXPIRE_MINUTES.",
    )
    include_short_code: bool = Field(
        default=True,
        description="Also issue a short, human-typable code alongside the QR token.",
    )


class PairingInvitationOut(OutSchema):
    invitation_id: uuid.UUID
    family_id: uuid.UUID
    child_profile_id: uuid.UUID
    status: PairingInvitationStatus
    expires_at: datetime
    created_at: datetime
    attempt_count: int
    short_code_prefix: str | None = None
    claimed_at: datetime | None = None
    claimed_device_id: uuid.UUID | None = None


class PairingInvitationCreated(PairingInvitationOut):
    """Returned once, at creation time only.

    ``claim_token`` is the value to encode in the QR code. The server stores
    only its hash, so it can never be retrieved again and is never logged.
    Do **not** encode a parent JWT or account details in the QR payload.
    """

    claim_token: str
    short_code: str | None = None


class DeviceRegistrationInfo(SchemaBase):
    """Minimal device metadata.

    Deliberately excluded: hardware serial, IMEI, MAC address, advertising id,
    phone number, installed-app inventory. None of those are needed for the
    product and all of them increase harm if breached.
    """

    platform: DevicePlatform = DevicePlatform.android
    app_version: str = Field(max_length=32, examples=["1.0.0"])
    os_version: str | None = Field(default=None, max_length=48, examples=["Android 16"])
    device_label: str | None = Field(default=None, max_length=80)
    device_model: str | None = Field(default=None, max_length=80)
    manufacturer: str | None = Field(default=None, max_length=80)
    timezone: str = Field(default="UTC", max_length=64)
    #: Stable per-install random id generated by the Child App. Makes repeated
    #: registration idempotent; must not be a hardware identifier.
    install_id: str | None = Field(default=None, min_length=8, max_length=64)

    @field_validator("timezone")
    @classmethod
    def _tz(cls, value: str) -> str:
        return validate_timezone(value)


class PairingClaimRequest(SchemaBase):
    claim_token: str | None = Field(default=None, min_length=20, max_length=512)
    short_code: str | None = Field(default=None, min_length=6, max_length=16)
    device: DeviceRegistrationInfo
    disclosure_version: str = Field(
        max_length=32,
        examples=["2026-01"],
        description="Version of the on-device disclosure the user acknowledged.",
    )
    disclosure_acknowledged: bool = Field(
        description="Must be true. The Child App shows the disclosure before claiming."
    )

    @field_validator("disclosure_acknowledged")
    @classmethod
    def _must_acknowledge(cls, value: bool) -> bool:
        if not value:
            raise ValueError("The on-device disclosure must be acknowledged before pairing.")
        return value


class PairingClaimResponse(OutSchema):
    device_id: uuid.UUID
    child_profile_id: uuid.UUID
    family_id: uuid.UUID
    device_access_token: str
    device_refresh_token: str
    token_type: str = "Bearer"
    expires_in: int
    refresh_expires_in: int
    status: DeviceStatus
    policy_version: int


# ---------------------------------------------------------------------------
# Device registration / heartbeat
# ---------------------------------------------------------------------------
class DeviceRegisterRequest(SchemaBase):
    """Completes or refreshes registration using the device's own credential."""

    device: DeviceRegistrationInfo
    capabilities: list[CapabilityReportItem] = Field(default_factory=list, max_length=64)
    permissions: list[PermissionReportItem] = Field(default_factory=list, max_length=64)


class DeviceHeartbeatRequest(SchemaBase):
    app_version: str | None = Field(default=None, max_length=32)
    os_version: str | None = Field(default=None, max_length=48)
    timezone: str | None = Field(default=None, max_length=64)
    battery_percent: int | None = Field(default=None, ge=0, le=100)
    charging: bool | None = None
    network_type: str | None = Field(default=None, max_length=16)
    applied_policy_version: int | None = Field(default=None, ge=0)

    @field_validator("timezone")
    @classmethod
    def _tz(cls, value: str | None) -> str | None:
        return validate_timezone(value) if value else value


class DeviceHeartbeatResponse(OutSchema):
    server_time: datetime
    policy_version: int
    policy_sync_required: bool
    pending_command_count: int
    #: Seconds the device should wait before its next poll.
    next_poll_after_seconds: int


class CapabilityReportItem(SchemaBase):
    capability_key: CapabilityKey
    support: CapabilitySupport
    permission_state: PermissionState = PermissionState.unknown
    os_api_level: int | None = Field(default=None, ge=1, le=100)
    #: Short, non-sensitive explanation the Parent App can display.
    note: str | None = Field(default=None, max_length=160)


class CapabilityReportRequest(SchemaBase):
    app_version: str | None = Field(default=None, max_length=32)
    capabilities: list[CapabilityReportItem] = Field(min_length=1, max_length=64)


class CapabilityOut(OutSchema):
    capability_key: CapabilityKey
    support: CapabilitySupport
    permission_state: PermissionState
    reported_at: datetime
    os_api_level: int | None = None


class PermissionReportItem(SchemaBase):
    permission_key: PermissionKey
    state: PermissionState
    note: str | None = Field(default=None, max_length=160)


class PermissionReportRequest(SchemaBase):
    app_version: str | None = Field(default=None, max_length=32)
    permissions: list[PermissionReportItem] = Field(min_length=1, max_length=64)


class PermissionOut(OutSchema):
    permission_key: PermissionKey
    state: PermissionState
    reported_at: datetime


# ---------------------------------------------------------------------------
# Parent-facing device views
# ---------------------------------------------------------------------------
class DeviceOut(OutSchema):
    id: uuid.UUID
    family_id: uuid.UUID
    child_profile_id: uuid.UUID
    device_label: str
    platform: DevicePlatform
    device_status: DeviceStatus
    app_version: str | None
    os_version: str | None
    device_model: str | None
    manufacturer: str | None
    timezone: str
    registered_at: datetime | None
    last_seen_at: datetime | None
    revoked_at: datetime | None
    #: Derived from `last_seen_at`; "online" is an inference, not a guarantee.
    presence: str = Field(
        default="unknown",
        description="online | recently_seen | offline | unknown, derived from last_seen_at.",
    )
    policy_version: int = 0
    applied_policy_version: int | None = None
    policy_sync_status: SyncStatus = SyncStatus.pending_sync
    policy_sync_detail: str | None = None
    policy_synced_at: datetime | None = None
    created_at: datetime


class DeviceDetailOut(DeviceOut):
    capabilities: list[CapabilityOut] = Field(default_factory=list)
    permissions: list[PermissionOut] = Field(default_factory=list)
    pending_command_count: int = 0


class DeviceLabelUpdate(SchemaBase):
    device_label: str = Field(min_length=1, max_length=80)


class DeviceRevokeRequest(SchemaBase):
    reason: str = Field(
        min_length=1,
        max_length=120,
        description="Recorded in the audit log and shown in the device history.",
    )


class DeviceRevokeResult(OutSchema):
    device_id: uuid.UUID
    device_status: DeviceStatus
    revoked_at: datetime
    sessions_revoked: int
    commands_cancelled: int
    push_tokens_deactivated: int


